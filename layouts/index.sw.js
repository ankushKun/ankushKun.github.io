// ---------------------------------------------------------------- kill switch

async function dropAll() {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith(PREFIX)).map((k) => caches.delete(k)));
}

async function retire() {
    killed = true;
    await dropAll();
    await self.registration.unregister();
    // Writes that were already under way when the switch was seen
    await sleep(3000);
    await dropAll();
}

/** /sw-disabled.txt on the server retires the worker even if no page script
 * runs. Asked (HEAD, no body) on every top-level page load, at most once a
 * second; force skips that gap (a page load that fell back to a saved copy). */
function maybeCheckKillSwitch(event, force) {
    const now = Date.now();
    if (killCheck || (!force && now - lastKillCheck < KILL_CHECK_GAP)) return;
    lastKillCheck = now;
    killCheck = fetch(KILL_URL, { method: 'HEAD', cache: 'no-store', credentials: 'same-origin' }).then((res) => {
        if (res.status === 200 && !/html/i.test(res.headers.get('content-type') || '')) return retire();
        return undefined;
    }).catch(() => {}).then(() => { killCheck = null; });
    event.waitUntil(killCheck);
}

// ---------------------------------------------------------------- messages

self.addEventListener('message', (event) => {
    const data = event.data || {};
    const port = event.ports && event.ports[0];
    const reply = (msg) => { if (port) port.postMessage(msg); };
    switch (data.type) {
        case 'HELLO': // a page reports the build it was rendered by
            event.waitUntil(noteBuild(data.build).catch(() => {}));
            reply({ build: BUILD, stale: stale() });
            break;
        case 'CLAIM': // first install: take over the page that registered us, if it is this build
            if (data.build === BUILD) event.waitUntil(self.clients.claim());
            reply({ build: BUILD });
            break;
        case 'ACTIVATE_IF_ALONE': // waiting worker: the only open tab already shows this build
            event.waitUntil((async () => {
                const wins = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
                const tops = wins.filter((w) => w.frameType !== 'nested');
                const sender = event.source && event.source.id;
                const alone = data.build === BUILD && tops.every((w) => w.id === sender);
                if (alone) await self.skipWaiting();
                reply({ build: BUILD, activated: alone });
            })());
            break;
        case 'SKIP_WAITING': // the visitor asked to reload into the new version
            self.skipWaiting();
            reply({ build: BUILD });
            break;
        case 'KILL':
            event.waitUntil(retire());
            reply({ build: BUILD });
            break;
        default:
            reply({ build: BUILD });
    }
});

// ---------------------------------------------------------------- strategies

/** Remember which build a page (window client) shows, for the requests that
 * page makes next: a promise of its build id. */
function servedPage(event, build) {
    const id = event.resultingClientId;
    if (!id) return;
    clientBuilds.set(id, build);
    if (clientBuilds.size > 20) clientBuilds.delete(clientBuilds.keys().next().value);
}

/** true when the page making this request is from another build, typically
 * the first page of a new deploy fetched through this older worker before it
 * knew about the deploy. Waits (at most BUILD_WAIT) for that page's marker,
 * which is read from its HTML as it arrives. */
async function otherBuildPage(event) {
    const pending = event.clientId && clientBuilds.get(event.clientId);
    if (!pending) return false;
    const build = await Promise.race([pending, sleep(BUILD_WAIT).then(() => null)]);
    return !!build && build !== BUILD;
}

/** Cache first. Unhashed files go to the network first once stale(), or when
 * the page asking for them is from another build. */
async function cacheFirst(event, req, cacheName, immutable) {
    const hit = await lookup(cacheName, req);
    if (hit && (immutable || !(stale() || await otherBuildPage(event)))) return hit;
    try {
        // A saved copy skipped for being from an older build: make sure the
        // browser's HTTP cache does not hand back that same old file either
        const res = hit ? await fetch(req, { cache: 'no-cache' }) : await fromNetwork(event, req);
        store(event, cacheName, req, res);
        // A server error does not beat a good saved copy
        return !res.ok && hit ? hit : res;
    } catch (err) {
        if (hit) return hit;
        throw err;
    }
}

/** Stale-while-revalidate for data files. */
async function staleWhileRevalidate(event, req) {
    const hit = await lookup(CACHES.data, req);
    const network = fetch(req).then((res) => { store(event, CACHES.data, req, res); return res; });
    if (hit && !stale() && !(await otherBuildPage(event))) {
        event.waitUntil(network.catch(() => {}));
        return hit;
    }
    try {
        const res = await network;
        return !res.ok && hit ? hit : res;
    } catch (err) {
        if (hit) return hit;
        throw err;
    }
}

/** Save a page of this build under its path. Never another build's page (it
 * announces a newer deploy instead), and never HTML without the marker:
 * alias redirect stubs (/wins/, renamed slugs) and other non-pages. */
async function storePage(key, html, res) {
    const found = html.match(MARKER);
    if (!found) return;
    if (found[1] !== BUILD) { await noteBuild(found[1]); return; }
    if (/<meta[^>]+http-equiv=["']?refresh/i.test(html)) return;
    await write(CACHES.pages, key, res);
    await trimPages();
    await fillBundles(html);
}

/** Network first with a short timeout for HTML: top-level navigations,
 * windows loading a page into the desktop, same-origin iframes. Offline, a
 * navigation falls back to the saved copy of that path (any query string),
 * then the offline page. */
async function networkFirstPage(event, req, isDocument) {
    const key = pageKey(req);
    const network = (async () => {
        const res = await fromNetwork(event, req);
        let build = Promise.resolve(null);
        if (cacheable(res) && /text\/html/i.test(res.headers.get('content-type') || '')) {
            const copy = res.clone();
            const html = res.clone().text();
            build = html.then((h) => (h.match(MARKER) || [])[1] || null, () => null);
            event.waitUntil(html.then((h) => storePage(key, h, copy)).catch(() => {}));
        }
        return { res, build };
    })();
    event.waitUntil(network.then(() => {}, () => {}));
    const fresh = (got) => { if (isDocument) servedPage(event, got.build); return got.res; };
    const saved = (res) => { if (isDocument) servedPage(event, Promise.resolve(BUILD)); return res; };

    const cached = await lookup(CACHES.pages, key);
    if (cached) {
        // Once a newer deploy is known this build's saved copy is the last
        // resort: a slow answer is still the current version, so wait for it
        // and fall back only on a network error or a very long wait. (Every
        // saved page is self-consistent: its bundles are saved with it.)
        const wait = stale() ? STALE_NAV_TIMEOUT : NAV_TIMEOUT;
        const got = await Promise.race([network.catch(() => null), sleep(wait).then(() => null)]);
        if (got && got.res.status < 500) return fresh(got);
        if (isDocument) maybeCheckKillSwitch(event, true);
        return saved(cached);
    }
    try {
        return fresh(await network);
    } catch (err) {
        if (!isDocument) throw err;
        maybeCheckKillSwitch(event, true);
        const fallback = await lookup(CACHES.pages, absolute(OFFLINE_URL));
        if (fallback) return saved(fallback);
        throw err;
    }
}

// ---------------------------------------------------------------- routing

self.addEventListener('fetch', (event) => {
    if (killed) return;
    const req = event.request;
    // Only plain same-origin GETs. Everything else (POST, range requests for
    // media, third parties: Gun relays, analytics, the link proxy, YouTube,
    // fonts, APIs) goes straight to the network and is never stored.
    if (req.method !== 'GET' || req.headers.has('range') || req.cache === 'no-store') return;
    let url;
    try { url = new URL(req.url); } catch (e) { return; }
    if (url.origin !== self.location.origin || NEVER.test(url.pathname) || MEDIA.test(url.pathname)) return;

    const path = url.pathname;
    let handler = null;
    if (PAYLOAD.test(path)) {
        // Emulators and games: stored the first time the app fetches them
        handler = () => cacheFirst(event, req, CACHES.payload, false);
    } else if (req.mode === 'navigate') {
        const isDocument = req.destination === 'document' || req.destination === '';
        if (isDocument) {
            maybeCheckKillSwitch(event);
            // A worker replaced mid-request may have recreated an old cache
            if (!swept && !stale()) { swept = true; event.waitUntil(sweep().catch(() => {})); }
        }
        handler = () => networkFirstPage(event, req, isDocument);
    } else if (FINGERPRINT.test(path)) {
        handler = () => cacheFirst(event, req, CACHES.static, true);
    } else if (IMAGE.test(path)) {
        handler = () => cacheFirst(event, req, CACHES.static, false);
    } else if (DATA.test(path)) {
        handler = () => staleWhileRevalidate(event, req);
    } else if (req.destination === '' && (path.endsWith('/') || path.endsWith('.html'))) {
        // A window fetching a page to show on the desktop
        handler = () => networkFirstPage(event, req, false);
    }
    if (!handler) return;
    // Keep an unused navigation preload from being cancelled noisily
    if (req.mode === 'navigate' && event.preloadResponse) event.waitUntil(event.preloadResponse.catch(() => {}));
    // A strategy that fails for any reason hands the request to the network
    event.respondWith(handler().catch(() => fetch(req)));
});
